-- Reconcile PRODUCTION's round_results / round_winners with the schema proven on dev
-- (secret-garden-frontend-dev/supabase/round_results.sql).
--
-- APPLIED to production (qudmeawkhzzvrpiljvav) on 2026-08-13. Kept in the repo as the record
-- of what was run, and because it is re-runnable: the pre-flight block and the
-- duplicate_object guards make a second execution a safe no-op.
--
-- Result: 21 result rows and 40 winner rows migrated in place with content byte-identical
-- before and after (verified by md5 over every row, plus a full row-dump diff). The resulting
-- schema was diffed against dev's and matches on columns, constraints and policies.
--
-- WHAT PRODUCTION HAS TODAY
--   both tables: `id bigint GENERATED BY DEFAULT AS IDENTITY` PRIMARY KEY, and every
--   business column NULLABLE. No unique constraint, no foreign key, no checks, and no index
--   other than the surrogate PK. Nothing prevents the same round being written twice.
--
-- WHAT THIS CHANGES IT TO
--   round_results keyed by round_number; round_winners keyed by (round_number, rank) — which
--   is what makes a duplicate write impossible and lets a writer use ON CONFLICT DO NOTHING;
--   a foreign key tying a podium to its summary row; NOT NULL + CHECK on every column that
--   should have had them; and the read index Daily Winners' "latest round" query wants.
--
-- SAFE IN PLACE. Verified against production's live data on 2026-08-13: 21 result rows, 40
-- winner rows, zero duplicate round_number, zero duplicate (round_number, rank), zero orphaned
-- winners, zero NULLs in any column that becomes NOT NULL, zero CHECK violations. No code
-- anywhere reads the surrogate `id` — every query in every repo selects business columns and
-- filters by round_number/rank — so dropping it breaks nothing.
--
-- The PRE-FLIGHT block below re-proves all of that AT RUN TIME and aborts the whole
-- transaction if anything has drifted since. Do not remove it: the data being clean today is
-- not a guarantee it is clean when this is actually executed.

begin;

-- ---------------------------------------------------------------------------------------
-- PRE-FLIGHT: refuse to migrate dirty data rather than fail halfway through.
-- ---------------------------------------------------------------------------------------
do $$
declare
  n bigint;
begin
  select count(*) into n from (
    select round_number from public.round_results group by round_number having count(*) > 1
  ) d;
  if n > 0 then raise exception 'ABORT: % duplicate round_number in round_results', n; end if;

  select count(*) into n from (
    select round_number, rank from public.round_winners
    group by round_number, rank having count(*) > 1
  ) d;
  if n > 0 then raise exception 'ABORT: % duplicate (round_number, rank) in round_winners', n; end if;

  select count(*) into n
    from public.round_winners w
    left join public.round_results r on r.round_number = w.round_number
   where r.round_number is null;
  if n > 0 then raise exception 'ABORT: % orphaned winner rows with no matching result', n; end if;

  select count(*) into n from public.round_results
   where round_number is null or target_traits is null
      or total_entrants is null or completed_at is null;
  if n > 0 then raise exception 'ABORT: % round_results rows hold NULLs in to-be-NOT-NULL columns', n; end if;

  select count(*) into n from public.round_winners
   where round_number is null or rank is null or wallet_address is null
      or flower_name is null or generation is null;
  if n > 0 then raise exception 'ABORT: % round_winners rows hold NULLs in to-be-NOT-NULL columns', n; end if;

  select count(*) into n from public.round_winners where rank < 1 or rank > 3 or generation < 0;
  if n > 0 then raise exception 'ABORT: % round_winners rows violate the rank/generation checks', n; end if;

  select count(*) into n from public.round_results where total_entrants < 0;
  if n > 0 then raise exception 'ABORT: % round_results rows have negative total_entrants', n; end if;

  raise notice 'pre-flight OK — data is clean, migrating';
end $$;

-- ---------------------------------------------------------------------------------------
-- 1. Drop the surrogate keys. Nothing reads `id`; dropping the column also drops its
--    identity sequence. The constraint is dropped first so the intent is explicit rather
--    than an implicit cascade.
-- ---------------------------------------------------------------------------------------
alter table public.round_results drop constraint if exists round_results_pkey;
alter table public.round_winners drop constraint if exists round_winners_pkey;

alter table public.round_results drop column if exists id;
alter table public.round_winners drop column if exists id;

-- ---------------------------------------------------------------------------------------
-- 2. Tighten nullability. Every one of these is already fully populated in production.
-- ---------------------------------------------------------------------------------------
alter table public.round_results
  alter column round_number   set not null,
  alter column target_traits  set not null,
  alter column total_entrants set not null,
  alter column completed_at   set not null,
  alter column created_at     set not null;

alter table public.round_winners
  alter column round_number   set not null,
  alter column rank           set not null,
  alter column wallet_address set not null,
  alter column flower_name    set not null,
  alter column generation     set not null,
  alter column created_at     set not null;

-- ---------------------------------------------------------------------------------------
-- 3. Keys. round_winners' composite key is the important one: it is what makes a second
--    write for a round conflict instead of silently duplicating the podium.
-- ---------------------------------------------------------------------------------------
do $$ begin
  alter table public.round_results add constraint round_results_pkey primary key (round_number);
exception when duplicate_table or duplicate_object then null; end $$;

do $$ begin
  alter table public.round_winners add constraint round_winners_pkey primary key (round_number, rank);
exception when duplicate_table or duplicate_object then null; end $$;

-- ---------------------------------------------------------------------------------------
-- 4. Checks + foreign key. A winner row without its round's summary would render as a podium
--    for a round the panel knows nothing about.
-- ---------------------------------------------------------------------------------------
do $$ begin
  alter table public.round_results
    add constraint round_results_total_entrants_check check (total_entrants >= 0);
exception when duplicate_object then null; end $$;

do $$ begin
  alter table public.round_winners
    add constraint round_winners_rank_check check (rank between 1 and 3);
exception when duplicate_object then null; end $$;

do $$ begin
  alter table public.round_winners
    add constraint round_winners_generation_check check (generation >= 0);
exception when duplicate_object then null; end $$;

do $$ begin
  alter table public.round_winners
    add constraint round_winners_round_fk
    foreign key (round_number) references public.round_results (round_number) on delete cascade;
exception when duplicate_object then null; end $$;

-- ---------------------------------------------------------------------------------------
-- 5. Read index for Daily Winners' max(round_number) lookup. (round_winners' own PK already
--    covers its per-round query.)
-- ---------------------------------------------------------------------------------------
create index if not exists round_results_round_number_desc
  on public.round_results (round_number desc);

-- ---------------------------------------------------------------------------------------
-- 6. RLS. Production already has it enabled with SELECT-only policies, but under different
--    policy NAMES than dev's file. Renaming them here means dev's round_results.sql can be
--    applied to production afterwards as a clean no-op, so the two projects stay one schema
--    with one source of truth. Read access is unchanged: public SELECT, no write policy —
--    writes go only through the service key inside the set-round-results edge function.
-- ---------------------------------------------------------------------------------------
alter table public.round_results enable row level security;
alter table public.round_winners enable row level security;

drop policy if exists "Public can view round results" on public.round_results;
drop policy if exists "Public can view round winners" on public.round_winners;

drop policy if exists "round_results is publicly readable" on public.round_results;
create policy "round_results is publicly readable"
  on public.round_results for select to anon, authenticated using (true);

drop policy if exists "round_winners is publicly readable" on public.round_winners;
create policy "round_winners is publicly readable"
  on public.round_winners for select to anon, authenticated using (true);

-- Explicitly ensure no write policy exists — "no policy" IS the security boundary.
drop policy if exists "round_results is anon-writable" on public.round_results;
drop policy if exists "round_winners is anon-writable" on public.round_winners;

commit;

